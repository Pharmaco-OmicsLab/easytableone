import { describe, it, expect } from "vitest";
import { generateDataQualityReport } from "./dataQualityReport";
import type { DataQualityRecord, Schema, AnalysisPlan } from "../types";

const dummySchema: Schema = { columns: [] };
const dummyPlan: AnalysisPlan = {
  rulesetVersion: "1.2",
  appVersion: "1.0",
  researchPopulation: "adult",
  studyDesign: "unspecified",
  unitSystem: "metric",
  groupingVariable: "Edema",
  includedVariables: [],
  variableConfig: {},
  showSMD: false,
  showPValue: true,
  multipleTestingCorrection: "none",
  randomSeed: 42,
  auditLog: [],
};

describe("generateDataQualityReport", () => {
  it("generates markdown report with summary and section listings", () => {
    const records: DataQualityRecord[] = [
      {
        finding: {
          checkId: "duplicateColumnNames",
          tier: "blocking",
          category: "format",
          title: "Duplicate Column Headers",
          detail: "Two columns are named 'Outcome'.",
          requirement: "Each column must have a unique header name.",
          remedy: "Rename one of them in Excel and re-upload.",
        },
        response: "fixed",
        timestamp: "2026-05-26T12:00:00.000Z",
        fixDetails: "Renamed Outcome to Outcome_2",
      },
      {
        finding: {
          checkId: "highMissingness_ColA",
          tier: "review",
          category: "quality",
          variable: "ColA",
          title: "Critical Missingness",
          detail: "Variable 'ColA' had 55.0% missingness.",
          remedy: "Acknowledge this high missingness to proceed, or exclude this column.",
          affectedCount: 55,
          affectedRowsSample: [1, 2, 3],
          sampleValues: ["10.5", "12.0"],
        },
        response: "acknowledged",
        timestamp: "2026-05-26T12:01:00.000Z",
      },
      {
        finding: {
          checkId: "noDictionarySheet",
          tier: "advisory",
          category: "beautify",
          title: "No Dictionary Sheet Imported",
          detail: "No data dictionary was imported.",
          remedy: "Importing a dictionary sheet helps automate clean labels.",
        },
        response: "acknowledged",
        timestamp: "2026-05-26T12:02:00.000Z",
      }
    ];

    const md = generateDataQualityReport(records, dummySchema, dummyPlan, "1.0.0-test", "2026-05-26T12:10:00.000Z");

    // Headings
    expect(md).toContain("# Data Quality Report");
    expect(md).toContain("Generated by EasyTableOne v1.0.0-test on 2026-05-26T12:10:00.000Z.");
    expect(md).toContain("**Research population:** Adult (bounds library: bounds_adults.json v1.0)");
    expect(md).toContain("**Unit system:** Metric");
    
    // Summary
    expect(md).toContain("- 3 findings detected");
    expect(md).toContain("- 1 fixed");
    expect(md).toContain("- 2 acknowledged (proceeded with known issue)");
    expect(md).toContain("- 0 overridden via \"acknowledge all\"");

    // Findings section
    expect(md).toContain("### Blocking issues (1)");
    expect(md).toContain("#### Duplicate Column Headers");
    expect(md).toContain("- **Tier:** Blocking  ·  **Category:** format");
    expect(md).toContain("- **What's wrong:** Two columns are named 'Outcome'.");
    expect(md).toContain("- **What the app requires:** Each column must have a unique header name.");
    expect(md).toContain("- **How to fix it:** Rename one of them in Excel and re-upload.");
    expect(md).toContain("- **User response:** fixed at 2026-05-26T12:00:00.000Z");
    expect(md).toContain("- **Fix details:** Renamed Outcome to Outcome_2");

    expect(md).toContain("### Review issues (1)");
    expect(md).toContain("#### Critical Missingness on `ColA`");
    expect(md).toContain("- **Affected:** 55 rows (sample rows 1, 2, 3)");

    expect(md).toContain("### Advisory — data-quality notes (0)");
    expect(md).toContain("### Advisory — improve your output (1)");
    expect(md).toContain("#### No Dictionary Sheet Imported");
    expect(md).toContain("- **What to check:** Importing a dictionary sheet helps automate clean labels.");
  });
});
