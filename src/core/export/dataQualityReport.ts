import type { DataQualityRecord, Schema, AnalysisPlan, DataQualityReport } from "../types";
import type { EDAResults } from "../eda/types";
import { loadBoundsLibrary } from "../bounds/boundsChecker";
import { generateEDAReportMarkdown } from "./edaReport";

export interface DataQualityReportOptions {
  qaReport?: DataQualityReport | null;
  edaResults?: EDAResults | null;
}

export function generateDataQualityReport(
  records: DataQualityRecord[],
  _schema: Schema,
  plan: AnalysisPlan,
  appVersion = "unknown",
  timestamp: string = new Date().toISOString(),
  options: DataQualityReportOptions = {},
): string {
  const total = records.length;
  const fixed = records.filter(r => r.response === "fixed").length;
  const acknowledged = records.filter(r => r.response === "acknowledged").length;
  const overridden = records.filter(r => r.response === "overridden").length;
  const applied = records.filter(r => r.response === "applied").length;
  const dismissed = records.filter(r => r.response === "dismissed").length;

  const blocking = records.filter(r => r.finding.tier === "blocking");
  const review = records.filter(r => r.finding.tier === "review");
  const advisoryQuality = records.filter(r => r.finding.tier === "advisory" && r.finding.category === "quality");
  const advisoryBeautify = records.filter(r => r.finding.tier === "advisory" && r.finding.category === "beautify");

  const lines: string[] = [];
  lines.push("# Data Quality Report\n");
  lines.push(`Generated by EasyTableOne v${appVersion} on ${timestamp}.\n`);
  lines.push(renderPopulationMetadata(plan));
  lines.push("");
  lines.push("## Summary");
  lines.push(`- ${total} findings detected`);
  lines.push(`- ${fixed} fixed`);
  lines.push(`- ${acknowledged} acknowledged (proceeded with known issue)`);
  lines.push(`- ${overridden} overridden via "acknowledge all"`);
  lines.push(`- ${applied} applied`);
  lines.push(`- ${dismissed} dismissed\n`);

  lines.push("## Findings\n");

  if (options.qaReport) {
    lines.push("## QA/QC Details\n");
    lines.push(`- Overall completeness: ${options.qaReport.overallCompletenessPercent.toFixed(1)}%`);
    options.qaReport.columns.forEach((col) => {
      lines.push(`- \`${col.name}\`: ${col.missingCount} missing (${col.missingPercent.toFixed(1)}%), cardinality ${col.cardinality}${col.isConstant ? ", constant value" : ""}`);
    });
    lines.push("");
  }

  lines.push(`### Blocking issues (${blocking.length})\n`);
  if (blocking.length === 0) {
    lines.push("No blocking issues detected.\n");
  } else {
    blocking.forEach(r => {
      lines.push(renderRecord(r) + "\n");
    });
  }

  lines.push(`### Review issues (${review.length})\n`);
  if (review.length === 0) {
    lines.push("No review issues detected.\n");
  } else {
    review.forEach(r => {
      lines.push(renderRecord(r) + "\n");
    });
  }

  lines.push(`### Advisory — data-quality notes (${advisoryQuality.length})\n`);
  if (advisoryQuality.length === 0) {
    lines.push("No data-quality notes detected.\n");
  } else {
    advisoryQuality.forEach(r => {
      lines.push(renderRecord(r) + "\n");
    });
  }

  lines.push(`### Advisory — improve your output (${advisoryBeautify.length})\n`);
  if (advisoryBeautify.length === 0) {
    lines.push("No beautification suggestions detected.\n");
  } else {
    advisoryBeautify.forEach(r => {
      lines.push(renderRecord(r) + "\n");
    });
  }

  if (options.edaResults) {
    lines.push(generateEDAReportMarkdown(options.edaResults, _schema));
  }

  return lines.join("\n");
}

function renderPopulationMetadata(plan: AnalysisPlan): string {
  const population = plan.researchPopulation ?? "adult";
  const studyDesign = plan.studyDesign ?? "unspecified";
  const unitSystem = plan.unitSystem ?? "metric";
  const unitLabel = unitSystem === "imperial" ? "Imperial" : "Metric";
  const designLabels: Record<string, string> = {
    unspecified: "Not specified",
    randomized_trial: "Randomised trial",
    observational: "Observational study",
    other: "Other",
  };
  if (population === "other") {
    return [
      "**Research population:** Other (sanity bounds checking disabled)",
      `**Study design:** ${designLabels[studyDesign] ?? studyDesign}`,
      `**Unit system:** ${unitLabel}`,
    ].join("\n");
  }
  const library = loadBoundsLibrary(population);
  const label = population === "pediatric" ? "Pediatric" : "Adult";
  const filename = population === "pediatric" ? "bounds_pediatric.json" : "bounds_adults.json";
  return [
    `**Research population:** ${label} (bounds library: ${filename} v${library?.version ?? "unknown"})`,
    `**Study design:** ${designLabels[studyDesign] ?? studyDesign}`,
    `**Unit system:** ${unitLabel}`,
  ].join("\n");
}

function renderRecord(record: DataQualityRecord): string {
  const f = record.finding;
  const lines: string[] = [];
  
  lines.push(`#### ${f.title}${f.variable ? ` on \`${f.variable}\`` : ""}`);
  lines.push(`- **Tier:** ${f.tier.charAt(0).toUpperCase() + f.tier.slice(1)}  ·  **Category:** ${f.category}`);
  lines.push(`- **What's wrong:** ${f.detail}`);
  if (f.requirement) {
    lines.push(`- **What the app requires:** ${f.requirement}`);
  }
  const label = f.tier === "advisory" ? "What to check" : "How to fix it";
  lines.push(`- **${label}:** ${f.remedy}`);
  
  const sampleRows = f.affectedRowsSample && f.affectedRowsSample.length > 0
    ? ` (sample rows ${f.affectedRowsSample.join(', ')})`
    : "";
  lines.push(`- **Affected:** ${f.affectedCount !== undefined ? `${f.affectedCount} rows` : "—"}${sampleRows}`);
  lines.push(`- **User response:** ${record.response} at ${record.timestamp}`);
  lines.push(`- **Fix details:** ${record.fixDetails ?? "—"}`);
  
  return lines.join("\n");
}
