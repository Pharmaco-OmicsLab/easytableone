import {
  Document,
  HeadingLevel,
  ImageRun,
  Packer,
  Paragraph,
  TextRun,
} from "docx";
import type { DataQualityRecord, Schema, AnalysisPlan, DataQualityReport } from "../types";
import type { EDAResults } from "../eda/types";
import { generateEDAReportMarkdown, generateEDAReportSectionHtml } from "./edaReport";
import { buildCorrelationSpec, buildMissingnessSpec } from "../eda/edaSpecBuilders";
import { vegaLiteSpecToPng } from "./vegaRender";

export interface DataQualityExportOptions {
  qaReport?: DataQualityReport | null;
  edaResults?: EDAResults | null;
}

export async function exportDataQualityDocx(
  records: DataQualityRecord[],
  _schema: Schema | null,
  _plan: AnalysisPlan | null,
  appVersion = "unknown",
  options: DataQualityExportOptions = {},
): Promise<Blob> {
  const children: any[] = [];

  // Title
  children.push(
    new Paragraph({
      text: "Data Quality Report",
      heading: HeadingLevel.HEADING_1,
      spacing: { after: 300 },
    })
  );

  const timestamp = new Date().toLocaleString();
  children.push(
    new Paragraph({
      children: [
        new TextRun({ text: `Generated by EasyTableOne v${appVersion} on ${timestamp}`, italics: true }),
      ],
      spacing: { after: 400 },
    })
  );

  // Summary statistics
  const total = records.length;
  const fixed = records.filter(r => r.response === "fixed").length;
  const acknowledged = records.filter(r => r.response === "acknowledged").length;
  const overridden = records.filter(r => r.response === "overridden").length;
  const applied = records.filter(r => r.response === "applied").length;
  const dismissed = records.filter(r => r.response === "dismissed").length;

  children.push(
    new Paragraph({
      text: "Summary Stats",
      heading: HeadingLevel.HEADING_2,
      spacing: { before: 200, after: 150 },
    })
  );

  const summaryItems = [
    `${total} findings detected`,
    `${fixed} fixed`,
    `${acknowledged} acknowledged`,
    `${overridden} overridden`,
    `${applied} applied`,
    `${dismissed} dismissed`,
  ];

  summaryItems.forEach(item => {
    children.push(
      new Paragraph({
        text: `\u2022 ${item}`,
        spacing: { after: 100 },
      })
    );
  });

  children.push(new Paragraph({ text: "", spacing: { after: 300 } }));

  if (options.qaReport) {
    children.push(
      new Paragraph({
        text: "QA/QC Details",
        heading: HeadingLevel.HEADING_2,
        spacing: { before: 300, after: 200 },
      })
    );
    children.push(
      new Paragraph({
        text: `Overall completeness: ${options.qaReport.overallCompletenessPercent.toFixed(1)}%`,
        spacing: { after: 100 },
      })
    );
    options.qaReport.columns.forEach((col) => {
      children.push(
        new Paragraph({
          text: `${col.name}: ${col.missingCount} missing (${col.missingPercent.toFixed(1)}%), cardinality ${col.cardinality}${col.isConstant ? ", constant value" : ""}`,
          spacing: { after: 80 },
        })
      );
    });
  }

  // Tiers
  const tiers = [
    { name: "Blocking Issues (Critical)", records: records.filter(r => r.finding.tier === "blocking") },
    { name: "Review Needed (Important)", records: records.filter(r => r.finding.tier === "review") },
    { name: "Advisory — data-quality notes", records: records.filter(r => r.finding.tier === "advisory" && r.finding.category === "quality") },
    { name: "Advisory — improve your output", records: records.filter(r => r.finding.tier === "advisory" && r.finding.category === "beautify") },
  ];

  tiers.forEach(tier => {
    children.push(
      new Paragraph({
        text: `${tier.name} (${tier.records.length})`,
        heading: HeadingLevel.HEADING_2,
        spacing: { before: 300, after: 200 },
      })
    );

    if (tier.records.length === 0) {
      children.push(
        new Paragraph({
          children: [new TextRun({ text: "No findings in this category.", italics: true })],
          spacing: { after: 200 },
        })
      );
    } else {
      tier.records.forEach(r => {
        const f = r.finding;
        children.push(
          new Paragraph({
            text: `${f.title}${f.variable ? ` (Variable: ${f.variable})` : ""}`,
            heading: HeadingLevel.HEADING_3,
            spacing: { before: 200, after: 100 },
          })
        );

        // Details
        children.push(
          new Paragraph({
            children: [
              new TextRun({ text: "What's wrong: ", bold: true }),
              new TextRun({ text: f.detail }),
            ],
            spacing: { after: 80 },
          })
        );

        if (f.requirement) {
          children.push(
            new Paragraph({
              children: [
                new TextRun({ text: "Requirement: ", bold: true }),
                new TextRun({ text: f.requirement }),
              ],
              spacing: { after: 80 },
            })
          );
        }

        const fixLabel = f.tier === "advisory" ? "What to check: " : "How to fix it: ";
        children.push(
          new Paragraph({
            children: [
              new TextRun({ text: fixLabel, bold: true }),
              new TextRun({ text: f.remedy }),
            ],
            spacing: { after: 80 },
          })
        );

        if (f.affectedRowsSample && f.affectedRowsSample.length > 0) {
          children.push(
            new Paragraph({
              children: [
                new TextRun({ text: "Affected: ", bold: true }),
                new TextRun({ text: `${f.affectedCount || f.affectedRowsSample.length} rows (sample rows: ${f.affectedRowsSample.join(", ")})` }),
              ],
              spacing: { after: 80 },
            })
          );
        }

        children.push(
          new Paragraph({
            children: [
              new TextRun({ text: "User Response: ", bold: true }),
              new TextRun({ text: `${r.response} at ${new Date(r.timestamp).toLocaleString()}` }),
            ],
            spacing: { after: 80 },
          })
        );

        if (r.fixDetails) {
          children.push(
            new Paragraph({
              children: [
                new TextRun({ text: "Fix Details: ", bold: true }),
                new TextRun({ text: r.fixDetails }),
              ],
              spacing: { after: 80 },
            })
          );
        }

        // Add a line divider or space
        children.push(new Paragraph({ text: "", spacing: { after: 150 } }));
      });
    }
  });

  if (options.edaResults) {
    const missingnessChartPng = await vegaLiteSpecToPng(buildMissingnessSpec(options.edaResults.missingness.perVariable));
    const correlationMatrixPng = options.edaResults.correlations.nContinuous >= 2
      ? await vegaLiteSpecToPng(buildCorrelationSpec(
          options.edaResults.correlations.pairs,
          options.edaResults.correlations.flagged,
          options.edaResults.correlations.variableOrder,
          _schema,
        ))
      : null;

    children.push(
      new Paragraph({
        text: "Exploratory Data Analysis",
        heading: HeadingLevel.HEADING_2,
        spacing: { before: 300, after: 200 },
      })
    );
    generateEDAReportMarkdown(options.edaResults, _schema)
      .split("\n")
      .filter((line) => line.trim().length > 0 && !line.startsWith("## "))
      .forEach((line) => {
        children.push(new Paragraph({ text: line, spacing: { after: 80 } }));
      });

    if (missingnessChartPng) {
      children.push(new Paragraph({ text: "Missingness summary", heading: HeadingLevel.HEADING_3, spacing: { before: 200, after: 100 } }));
      children.push(
        new Paragraph({
          children: [
            new ImageRun({
              type: "png",
              data: base64ToArrayBuffer(missingnessChartPng),
              transformation: { width: 500, height: 260 },
              inline: true,
            } as any),
          ],
          spacing: { after: 150 },
        })
      );
    }

    if (correlationMatrixPng) {
      children.push(new Paragraph({ text: "Correlation matrix", heading: HeadingLevel.HEADING_3, spacing: { before: 200, after: 100 } }));
      children.push(
        new Paragraph({
          children: [
            new ImageRun({
              type: "png",
              data: base64ToArrayBuffer(correlationMatrixPng),
              transformation: { width: 500, height: 500 },
              inline: true,
            } as any),
          ],
          spacing: { after: 150 },
        })
      );
    }

    if (options.edaResults.missingness.heatmapPng) {
      children.push(new Paragraph({ text: "Missingness heatmap", heading: HeadingLevel.HEADING_3, spacing: { before: 200, after: 100 } }));
      children.push(
        new Paragraph({
          children: [
            new ImageRun({
              type: "png",
              data: base64ToArrayBuffer(options.edaResults.missingness.heatmapPng),
              transformation: { width: 500, height: 300 },
              inline: true,
            } as any),
          ],
          spacing: { after: 150 },
        })
      );
    }

    options.edaResults.bivariate?.plots.forEach((plot) => {
      children.push(new Paragraph({ text: plot.displayLabel, heading: HeadingLevel.HEADING_3, spacing: { before: 200, after: 100 } }));
      children.push(
        new Paragraph({
          children: [
            new ImageRun({
              type: "png",
              data: base64ToArrayBuffer(plot.png),
              transformation: { width: 360, height: 240 },
              inline: true,
            } as any),
          ],
          spacing: { after: 150 },
        })
      );
    });
  }

  const doc = new Document({
    creator: `EasyTableOne v${appVersion}`,
    title: "Data Quality Report",
    sections: [
      {
        properties: {},
        children,
      },
    ],
  });

  return await Packer.toBlob(doc);
}

export function exportDataQualityPdf(
  records: DataQualityRecord[],
  schema: Schema | null,
  _plan: AnalysisPlan | null,
  appVersion = "unknown",
  options: DataQualityExportOptions = {},
) {
  const timestamp = new Date().toLocaleString();
  const total = records.length;
  const fixed = records.filter(r => r.response === "fixed").length;
  const acknowledged = records.filter(r => r.response === "acknowledged").length;
  const overridden = records.filter(r => r.response === "overridden").length;
  const applied = records.filter(r => r.response === "applied").length;
  const dismissed = records.filter(r => r.response === "dismissed").length;

  const blocking = records.filter(r => r.finding.tier === "blocking");
  const review = records.filter(r => r.finding.tier === "review");
  const advisoryQuality = records.filter(r => r.finding.tier === "advisory" && r.finding.category === "quality");
  const advisoryBeautify = records.filter(r => r.finding.tier === "advisory" && r.finding.category === "beautify");

  const renderFindingCard = (r: DataQualityRecord, borderColor: string, bgColor: string, badgeBg: string, badgeText: string) => {
    const f = r.finding;
    return `
      <div style="border-left: 4px solid ${borderColor}; background-color: ${bgColor}; padding: 16px; border-radius: 6px; margin-bottom: 16px; box-shadow: 0 1px 2px rgba(0,0,0,0.05); text-align: left;">
        <div style="display: flex; justify-content: space-between; align-items: flex-start; margin-bottom: 8px;">
          <h4 style="margin: 0; font-size: 15px; font-weight: 700; color: #111827;">${f.title}</h4>
          ${f.variable ? `<span style="background-color: ${badgeBg}; color: ${badgeText}; font-family: monospace; font-size: 11px; padding: 2px 6px; border-radius: 4px; font-weight: 600;">Variable: ${f.variable}</span>` : ""}
        </div>
        <p style="margin: 0 0 8px 0; font-size: 13.5px; color: #374151;"><strong>What's wrong:</strong> ${f.detail}</p>
        ${f.requirement ? `<p style="margin: 0 0 8px 0; font-size: 13.5px; color: #374151;"><strong>Requirement:</strong> ${f.requirement}</p>` : ""}
        <p style="margin: 0 0 8px 0; font-size: 13.5px; color: #374151;"><strong>${f.tier === "advisory" ? "What to check" : "How to fix it"}:</strong> ${f.remedy}</p>
        ${f.affectedRowsSample && f.affectedRowsSample.length > 0 ? `<p style="margin: 0 0 8px 0; font-size: 13.5px; color: #4b5563; font-style: italic;">Affected rows: ${f.affectedRowsSample.join(", ")}</p>` : ""}
        <div style="margin-top: 12px; padding-top: 8px; border-top: 1px dashed rgba(0,0,0,0.05); font-size: 12px; color: #6b7280; display: flex; justify-content: space-between;">
          <span><strong>User Response:</strong> ${r.response}</span>
          <span>${new Date(r.timestamp).toLocaleString()}</span>
        </div>
        ${r.fixDetails ? `<p style="margin: 6px 0 0 0; font-size: 12px; color: #4b5563;"><strong>Fix details:</strong> ${r.fixDetails}</p>` : ""}
      </div>
    `;
  };

  const html = `
    <!DOCTYPE html>
    <html>
    <head>
      <meta charset="utf-8">
      <title>Data Quality Report</title>
      <style>
        body {
          font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif;
          max-width: 850px;
          margin: 0 auto;
          padding: 30px;
          color: #374151;
          line-height: 1.5;
        }
        h1 { font-size: 26px; font-weight: 800; color: #111827; margin-bottom: 5px; text-align: left; }
        .meta { font-size: 13px; color: #6b7280; margin-bottom: 25px; text-align: left; }
        .summary-card { background: #f9fafb; border: 1px solid #e5e7eb; border-radius: 8px; padding: 20px; margin-bottom: 30px; }
        .summary-card h3 { margin-top: 0; margin-bottom: 12px; font-size: 16px; color: #111827; text-align: left; }
        .stats-grid { display: grid; grid-template-columns: repeat(3, 1fr); gap: 15px; }
        .stat-item { background: white; border: 1px solid #f3f4f6; padding: 12px; border-radius: 6px; text-align: center; }
        .stat-val { font-size: 18px; font-weight: 700; color: #111827; }
        .stat-lbl { font-size: 11px; color: #6b7280; text-transform: uppercase; margin-top: 2px; }
        h2 { font-size: 18px; font-weight: 700; color: #111827; margin-top: 30px; margin-bottom: 15px; border-bottom: 1px solid #e5e7eb; padding-bottom: 6px; text-align: left; }
        .no-findings { font-style: italic; color: #9ca3af; font-size: 13.5px; text-align: left; }
        .eda-summary { font-size: 13.5px; text-align: left; background: #f9fafb; border: 1px solid #e5e7eb; padding: 14px; border-radius: 6px; margin-bottom: 16px; }
        .eda-img { max-width: 100%; height: auto; border: 1px solid #e5e7eb; border-radius: 6px; margin: 8px 0 16px; }
        .eda-grid { display: grid; grid-template-columns: repeat(2, minmax(0, 1fr)); gap: 16px; }
        figure { margin: 0; break-inside: avoid; }
        figcaption { font-weight: 700; font-size: 13px; margin-bottom: 4px; text-align: left; }
        @media print {
          body { padding: 0; }
          .no-print { display: none; }
        }
      </style>
    </head>
    <body>
      <div style="display: flex; justify-content: space-between; align-items: center; border-bottom: 2px solid #e5e7eb; padding-bottom: 10px;">
        <h1 style="margin: 0;">Data Quality Report</h1>
        <button class="no-print" onclick="window.print()" style="background: #2563eb; color: white; border: none; padding: 8px 16px; border-radius: 6px; font-weight: 600; cursor: pointer; font-size: 13px;">Print / Save as PDF</button>
      </div>
      <div class="meta" style="margin-top: 8px;">Generated by EasyTableOne v${appVersion} on ${timestamp}</div>
      
      <div class="summary-card">
        <h3>Summary Stats</h3>
        <div class="stats-grid">
          <div class="stat-item"><div class="stat-val">${total}</div><div class="stat-lbl">Findings</div></div>
          <div class="stat-item"><div class="stat-val">${fixed}</div><div class="stat-lbl">Fixed</div></div>
          <div class="stat-item"><div class="stat-val">${acknowledged}</div><div class="stat-lbl">Acknowledged</div></div>
          <div class="stat-item"><div class="stat-val">${overridden}</div><div class="stat-lbl">Overridden</div></div>
          <div class="stat-item"><div class="stat-val">${applied}</div><div class="stat-lbl">Applied</div></div>
          <div class="stat-item"><div class="stat-val">${dismissed}</div><div class="stat-lbl">Dismissed</div></div>
        </div>
      </div>

      <h2>Blocking Issues (Critical) (${blocking.length})</h2>
      ${blocking.length === 0 ? '<p class="no-findings">No blocking issues detected.</p>' : blocking.map(r => renderFindingCard(r, '#ef4444', '#fef2f2', '#fee2e2', '#991b1b')).join("")}

      <h2>Review Needed (Important) (${review.length})</h2>
      ${review.length === 0 ? '<p class="no-findings">No review issues detected.</p>' : review.map(r => renderFindingCard(r, '#f59e0b', '#fffbeb', '#fef3c7', '#92400e')).join("")}

      <h2>Advisory — Data Quality Notes (${advisoryQuality.length})</h2>
      ${advisoryQuality.length === 0 ? '<p class="no-findings">No data quality warnings detected.</p>' : advisoryQuality.map(r => renderFindingCard(r, '#3b82f6', '#eff6ff', '#dbeafe', '#1e40af')).join("")}

      <h2>Advisory — Improve Your Output (${advisoryBeautify.length})</h2>
      ${advisoryBeautify.length === 0 ? '<p class="no-findings">No beautification recommendations detected.</p>' : advisoryBeautify.map(r => renderFindingCard(r, '#10b981', '#ecfdf5', '#d1fae5', '#065f46')).join("")}

      ${options.qaReport ? `
        <h2>QA/QC Details</h2>
        <p><strong>Overall completeness:</strong> ${options.qaReport.overallCompletenessPercent.toFixed(1)}%</p>
        ${options.qaReport.columns.map((col) => `
          <p style="font-size: 13.5px; margin: 4px 0;">
            <strong>${col.name}</strong>: ${col.missingCount} missing (${col.missingPercent.toFixed(1)}%), cardinality ${col.cardinality}${col.isConstant ? ", constant value" : ""}
          </p>
        `).join("")}
      ` : ""}

      ${options.edaResults ? generateEDAReportSectionHtml(options.edaResults, schema) : ""}

      <script>
        window.onload = () => {
          setTimeout(() => { window.print(); }, 500);
        };
      </script>
    </body>
    </html>
  `;

  const printWindow = window.open("", "_blank");
  if (printWindow) {
    printWindow.document.open();
    printWindow.document.write(html);
    printWindow.document.close();
  } else {
    alert("Popup blocked! Please allow popups to export the PDF.");
  }
}

function base64ToArrayBuffer(base64: string): ArrayBuffer {
  const binaryString = atob(base64);
  const len = binaryString.length;
  const bytes = new Uint8Array(len);
  for (let i = 0; i < len; i++) {
    bytes[i] = binaryString.charCodeAt(i);
  }
  return bytes.buffer;
}
